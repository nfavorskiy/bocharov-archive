    <p>Существенным вкладом Бочарова и его единомышленников на излёте СССР стало создание Советского общества урбанистов (СОУ). В середине 1980-х Юрий Петрович предложил организовать Совет по градостроительству при Союзе архитекторов СССР, куда вошли специалисты разных специальностей, работающие в области планировки и застройки населённых мест.</p>
    <p>На основе этого Совета в 1987 году было создано Советское общество урбанистов, а Бочаров избран его президентом (первым и последним). В августе 1989 года в Москве и Переславле-Залесском прошла первая в СССР Международная конференция урбанистов, на которой был принят Устав Общества.</p>

